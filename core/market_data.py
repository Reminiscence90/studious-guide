"""Candles (OHLC bars) for the trade review chart: download, upload, cache, resample.

Bars are stored in the ``price_bars`` table with UTC open times, keyed by chart symbol
(``ES=F``, ``EURUSD=X``, ``TSLA``...) and interval. Sources:

* **Yahoo Finance** (default, no API key). Intraday history is limited: 1-minute bars for
  about the last 30 days, 5–30 minute bars for 60 days, hourly bars for 2 years.
* **Uploaded CSV** with time/open/high/low/close(/volume) columns, e.g. TradingView's
  "Export chart data". Use this for your broker's exact prices or for older trades.
* **Demo** bars generated by the seed command for the sample trades.

A coarser interval is built from cached finer bars when possible, so one upload of
1-minute bars serves every interval.
"""

from __future__ import annotations

import json
import math
import urllib.error
import urllib.parse
import urllib.request
from collections.abc import Callable, Iterable
from datetime import UTC, datetime, timedelta
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

import pandas as pd
from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from core.models import PriceBar

# label -> seconds, finest first
INTERVALS: dict[str, int] = {
    "1m": 60,
    "5m": 300,
    "15m": 900,
    "30m": 1800,
    "1h": 3600,
    "4h": 14400,
    "1d": 86400,
}
# How far back Yahoo serves each interval (4h is resampled from 1h).
YAHOO_LOOKBACK: dict[str, timedelta] = {
    "1m": timedelta(days=29),
    "5m": timedelta(days=59),
    "15m": timedelta(days=59),
    "30m": timedelta(days=59),
    "1h": timedelta(days=729),
    "4h": timedelta(days=729),
    "1d": timedelta(days=365 * 30),
}
# Longest window Yahoo returns in one request for each intraday interval.
YAHOO_MAX_SPAN: dict[str, timedelta] = {"1m": timedelta(days=7)}
BAR_COLUMNS = ["time", "open", "high", "low", "close", "volume"]
MAX_TRADE_BARS = 240  # auto interval keeps the trade itself within this many bars

Fetcher = Callable[[str, str, datetime, datetime], pd.DataFrame]


class MarketDataError(RuntimeError):
    """Candles could not be downloaded or parsed."""


# --------------------------------------------------------------------------- time


def zone(name: str | None) -> ZoneInfo:
    try:
        return ZoneInfo(name or "UTC")
    except (ZoneInfoNotFoundError, ValueError):
        return ZoneInfo("UTC")


def to_utc(local: datetime, tz_name: str | None) -> datetime:
    """Naive local time in ``tz_name`` → naive UTC."""
    if local.tzinfo is None:
        local = local.replace(tzinfo=zone(tz_name))
    return local.astimezone(UTC).replace(tzinfo=None)


def from_utc(utc: datetime, tz_name: str | None) -> datetime:
    """Naive UTC → naive local time in ``tz_name``."""
    return utc.replace(tzinfo=UTC).astimezone(zone(tz_name)).replace(tzinfo=None)


# --------------------------------------------------------------------------- intervals


def auto_interval(
    entry_utc: datetime,
    exit_utc: datetime | None,
    now: datetime,
    *,
    history_limits: bool = True,
    local_intervals: Iterable[str] = (),
) -> str:
    """Finest interval that shows the whole trade in at most ``MAX_TRADE_BARS`` bars.

    With ``history_limits`` the interval must also be one Yahoo still serves for a trade
    this old, unless candles at that interval or finer are already stored locally
    (``local_intervals``, e.g. an uploaded CSV covering the trade).
    """
    end = exit_utc or now
    holding = max((end - entry_utc).total_seconds(), 60)
    age = now - entry_utc
    local = [INTERVALS[i] for i in local_intervals]
    for label, seconds in INTERVALS.items():
        if holding / seconds > MAX_TRADE_BARS:
            continue
        available = (
            not history_limits or age <= YAHOO_LOOKBACK[label] or any(s <= seconds for s in local)
        )
        if available:
            return label
    return "1d"


def local_intervals(
    session: Session, chart_symbol: str, start: datetime, end: datetime, source: str = "csv"
) -> list[str]:
    """Intervals with stored candles of ``source`` between ``start`` and ``end``."""
    rows = session.execute(
        select(PriceBar.interval)
        .where(
            PriceBar.chart_symbol == chart_symbol,
            PriceBar.source == source,
            PriceBar.time >= start,
            PriceBar.time <= end,
        )
        .distinct()
    ).scalars()
    return [r for r in rows if r in INTERVALS]


def review_window(
    entry_utc: datetime, exit_utc: datetime | None, interval: str, now: datetime
) -> tuple[datetime, datetime]:
    """Time range to load: the trade plus context before and after (at least 60 bars)."""
    step = timedelta(seconds=INTERVALS[interval])
    end = exit_utc or now
    pad = max(step * 60, (end - entry_utc) * 0.5)
    return entry_utc - pad, min(end + pad, now)


def floor_time(t: datetime, interval: str) -> datetime:
    """Open time of the bar that contains ``t`` (bars aligned to the UTC epoch)."""
    seconds = INTERVALS[interval]
    epoch = int(t.replace(tzinfo=UTC).timestamp())
    return datetime.fromtimestamp(epoch - epoch % seconds, UTC).replace(tzinfo=None)


def infer_interval(times: Iterable[datetime]) -> str:
    """Closest known interval to the typical spacing between bar times."""
    ts = pd.Series(sorted(set(times)))
    if len(ts) < 2:
        return "1d"
    spacing = ts.diff().dropna().dt.total_seconds().median()
    return min(INTERVALS, key=lambda k: abs(math.log(INTERVALS[k] / max(spacing, 1))))


def resample(bars: pd.DataFrame, interval: str) -> pd.DataFrame:
    """Aggregate finer bars into ``interval`` bars (UTC-epoch aligned)."""
    if bars.empty:
        return bars
    rule = f"{INTERVALS[interval]}s"
    out = (
        bars.set_index("time")
        .resample(rule, label="left", closed="left")
        .agg({"open": "first", "high": "max", "low": "min", "close": "last", "volume": "sum"})
        .dropna(subset=["open"])
        .reset_index()
    )
    return out[BAR_COLUMNS]


# --------------------------------------------------------------------------- Yahoo


def _http_get_json(url: str) -> dict:
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 trade-journal"})
    with urllib.request.urlopen(request, timeout=20) as response:
        return json.load(response)


def parse_yahoo_chart(payload: dict) -> pd.DataFrame:
    """Turn a Yahoo ``/v8/finance/chart`` response into bars (UTC times)."""
    chart = payload.get("chart") or {}
    if chart.get("error"):
        err = chart["error"]
        raise MarketDataError(f"Yahoo Finance: {err.get('description') or err.get('code')}")
    results = chart.get("result") or []
    if not results or not results[0].get("timestamp"):
        return pd.DataFrame(columns=BAR_COLUMNS)
    result = results[0]
    quote = (result.get("indicators") or {}).get("quote", [{}])[0]
    df = pd.DataFrame(
        {
            "time": pd.to_datetime(result["timestamp"], unit="s"),
            "open": quote.get("open"),
            "high": quote.get("high"),
            "low": quote.get("low"),
            "close": quote.get("close"),
            "volume": quote.get("volume"),
        }
    )
    return df.dropna(subset=["open", "high", "low", "close"]).reset_index(drop=True)


def fetch_yahoo(
    ticker: str,
    interval: str,
    start: datetime,
    end: datetime,
    get_json: Callable[[str], dict] = _http_get_json,
) -> pd.DataFrame:
    """Download bars from Yahoo Finance (UTC, naive datetimes). 4h is built from 1h."""
    if interval == "4h":
        return resample(fetch_yahoo(ticker, "1h", start, end, get_json), "4h")
    max_span = YAHOO_MAX_SPAN.get(interval)
    chunks: list[pd.DataFrame] = []
    chunk_start = start
    while chunk_start < end:
        chunk_end = min(end, chunk_start + max_span) if max_span else end
        params = urllib.parse.urlencode(
            {
                "period1": int(chunk_start.replace(tzinfo=UTC).timestamp()),
                "period2": int(chunk_end.replace(tzinfo=UTC).timestamp()),
                "interval": "60m" if interval == "1h" else interval,
                "includePrePost": "false",
            }
        )
        url = (
            "https://query2.finance.yahoo.com/v8/finance/chart/"
            f"{urllib.parse.quote(ticker)}?{params}"
        )
        try:
            chunks.append(parse_yahoo_chart(get_json(url)))
        except urllib.error.HTTPError as exc:
            raise MarketDataError(f"Yahoo Finance returned HTTP {exc.code} for {ticker}") from exc
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            raise MarketDataError(f"Could not reach Yahoo Finance: {exc}") from exc
        chunk_start = chunk_end
    if not chunks:
        return pd.DataFrame(columns=BAR_COLUMNS)
    df = pd.concat(chunks, ignore_index=True).drop_duplicates("time").sort_values("time")
    return df.reset_index(drop=True)


# --------------------------------------------------------------------------- CSV upload

_TIME_NAMES = ("time", "datetime", "date", "timestamp", "date/time", "opentime", "gmttime")


def parse_ohlc_csv(df: pd.DataFrame, tz_name: str | None = "UTC") -> pd.DataFrame:
    """Read an OHLC export (TradingView "Export chart data", MT5, broker CSVs...).

    Needs a time column and open/high/low/close; volume is optional. Numeric times are
    Unix seconds (or milliseconds) in UTC; text times are read in ``tz_name``.
    """
    cols = {"".join(ch for ch in str(c).lower() if ch.isalnum() or ch == "/"): c for c in df}
    time_col = next((cols[n] for n in _TIME_NAMES if n in cols), None)
    missing = [n for n in ("open", "high", "low", "close") if n not in cols]
    if time_col is None or missing:
        raise MarketDataError(
            "The CSV needs a time column and open, high, low and close columns"
            + (f" (missing: {', '.join(missing)})" if missing else "")
        )
    raw_time = df[time_col]
    numeric = pd.to_numeric(raw_time, errors="coerce")
    if numeric.notna().all():
        unit = "ms" if numeric.median() > 1e11 else "s"
        times = pd.to_datetime(numeric, unit=unit)
    else:
        parsed = pd.to_datetime(raw_time, utc=False, format="mixed")
        if parsed.dt.tz is not None:
            times = parsed.dt.tz_convert("UTC").dt.tz_localize(None)
        else:
            times = parsed.map(lambda t: to_utc(t.to_pydatetime(), tz_name))
    out = pd.DataFrame(
        {
            "time": pd.to_datetime(times),
            "open": pd.to_numeric(df[cols["open"]], errors="coerce"),
            "high": pd.to_numeric(df[cols["high"]], errors="coerce"),
            "low": pd.to_numeric(df[cols["low"]], errors="coerce"),
            "close": pd.to_numeric(df[cols["close"]], errors="coerce"),
            "volume": pd.to_numeric(df[cols["volume"]], errors="coerce")
            if "volume" in cols
            else None,
        }
    )
    out = out.dropna(subset=["open", "high", "low", "close"]).drop_duplicates("time")
    if out.empty:
        raise MarketDataError("No valid candles found in the CSV")
    return out.sort_values("time").reset_index(drop=True)


# --------------------------------------------------------------------------- cache


def store_bars(
    session: Session, chart_symbol: str, interval: str, bars: pd.DataFrame, source: str
) -> int:
    """Insert or replace bars in the cache. Returns the number of bars stored."""
    if bars.empty:
        return 0
    times = [t.to_pydatetime() for t in pd.to_datetime(bars["time"])]
    session.execute(
        delete(PriceBar).where(
            PriceBar.chart_symbol == chart_symbol,
            PriceBar.interval == interval,
            PriceBar.time >= min(times),
            PriceBar.time <= max(times),
        )
    )
    session.add_all(
        PriceBar(
            chart_symbol=chart_symbol,
            interval=interval,
            time=t,
            open=float(r.open),
            high=float(r.high),
            low=float(r.low),
            close=float(r.close),
            volume=None if r.volume is None or pd.isna(r.volume) else float(r.volume),
            source=source,
        )
        for t, r in zip(times, bars.itertuples(), strict=True)
    )
    session.flush()
    return len(times)


def import_ohlc(
    session: Session, chart_symbol: str, df: pd.DataFrame, tz_name: str | None = "UTC"
) -> tuple[str, int]:
    """Store an uploaded OHLC CSV for ``chart_symbol``. Returns (interval, bar count)."""
    bars = parse_ohlc_csv(df, tz_name)
    interval = infer_interval(bars["time"])
    return interval, store_bars(session, chart_symbol, interval, bars, "csv")


def cached_bars(
    session: Session, chart_symbol: str, interval: str, start: datetime, end: datetime
) -> tuple[pd.DataFrame, str | None]:
    """Cached bars at ``interval``, else resampled from the finest cached interval that has
    data in the range. Returns (bars, source)."""
    for label in [interval, *[k for k in INTERVALS if INTERVALS[k] < INTERVALS[interval]]]:
        rows = session.execute(
            select(PriceBar)
            .where(
                PriceBar.chart_symbol == chart_symbol,
                PriceBar.interval == label,
                PriceBar.time >= start - timedelta(seconds=INTERVALS[interval]),
                PriceBar.time <= end,
            )
            .order_by(PriceBar.time)
        ).scalars()
        bars = pd.DataFrame(
            [(b.time, b.open, b.high, b.low, b.close, b.volume, b.source) for b in rows],
            columns=[*BAR_COLUMNS, "source"],
        )
        if bars.empty:
            continue
        source = str(bars["source"].mode().iat[0])
        bars = bars[BAR_COLUMNS]
        if label != interval:
            bars = resample(bars, interval)
        return bars.reset_index(drop=True), source
    return pd.DataFrame(columns=BAR_COLUMNS), None


def _covers(bars: pd.DataFrame, start: datetime, end: datetime, interval: str) -> bool:
    if bars.empty:
        return False
    # Markets close at weekends and holidays, so allow a few days without bars at
    # either end of the window before deciding the cache is incomplete.
    slack = timedelta(seconds=INTERVALS[interval] * 3) + timedelta(days=3)
    first, last = bars["time"].iloc[0], bars["time"].iloc[-1]
    return first <= start + slack and last >= end - slack


def get_bars(
    session: Session,
    chart_symbol: str,
    interval: str,
    start: datetime,
    end: datetime,
    fetch: Fetcher | None = fetch_yahoo,
) -> tuple[pd.DataFrame, str | None]:
    """Bars for the review chart: from the cache when it covers the range (uploaded bars
    are always used as they are), otherwise downloaded and cached.

    Returns (bars, source). ``fetch=None`` never downloads.
    """
    bars, source = cached_bars(session, chart_symbol, interval, start, end)
    if source == "csv" or fetch is None or _covers(bars, start, end, interval):
        return bars, source
    downloaded = fetch(chart_symbol, interval, start, end)
    if downloaded.empty:
        return bars, source
    store_bars(session, chart_symbol, interval, downloaded, getattr(fetch, "source", "yahoo"))
    return cached_bars(session, chart_symbol, interval, start, end)


def utcnow() -> datetime:
    return datetime.now(UTC).replace(tzinfo=None)
